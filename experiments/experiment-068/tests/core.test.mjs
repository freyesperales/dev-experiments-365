import { test } from 'node:test';
import assert from 'node:assert/strict';
import { readFileSync } from 'node:fs';
import { loadCore } from '../tools/load-core.mjs';
import { makeZip } from '../tools/zipwrite.mjs';
import * as fx from '../tools/make-fixtures.mjs';

const S = loadCore();
const enc = s => new TextEncoder().encode(s);
const near = (a, b, e = 0.01) => assert.ok(Math.abs(a - b) <= e, `${a} !~ ${b}`);

test('parseDuration handles every slicer spelling', () => {
  assert.equal(S.parseDuration('1h 17m 40s'), 4660);
  assert.equal(S.parseDuration('2d 3h 4m 5s'), 183845);
  assert.equal(S.parseDuration('23m 5s'), 1385);
  assert.equal(S.parseDuration('5400'), 5400);
  assert.equal(S.parseDuration('nonsense'), null);
  assert.equal(S.parseDuration(null), null);
});

test('Bambu G-code header', () => {
  const j = S.analyzeText('b.gcode', fx.bambuGcode);
  assert.equal(j.slicer, 'BambuStudio 01.09.00.70');
  assert.equal(j.timeS, 4660);
  near(j.gramsTotal, 15.27);
  assert.equal(j.filaments[0].type, 'PLA');
  assert.equal(j.layers, 120);
  assert.equal(j.layerHeight, 0.2);
  assert.equal(j.printer, 'Bambu Lab A1');
});

test('PrusaSlicer G-code footer', () => {
  const j = S.analyzeText('p.gcode', fx.prusaGcode);
  assert.equal(j.slicer, 'PrusaSlicer 2.7.1');
  assert.equal(j.timeS, 11112);
  near(j.gramsTotal, 24.4);
  assert.equal(j.filaments[0].type, 'PETG');
  near(j.slicerCost, 0.61);
});

test('Cura has only metres: grams are estimated from geometry and flagged', () => {
  const j = S.analyzeText('c.gcode', fx.curaGcode);
  assert.equal(j.timeS, 5400);
  assert.equal(j.filaments[0].estimated, true);
  // 3.21 m of 1.75 mm PLA at 1.24 g/cm3 = 9.57 g
  near(j.gramsTotal, 9.57, 0.05);
  assert.equal(j.layers, 150);
});

test('multi-material extruder lists are summed per filament', () => {
  const j = S.analyzeText('m.gcode', '; generated by OrcaSlicer 2.1.1 on 2026-01-01\n; filament used [g] = 3.5, 1.5\n; filament_type = PLA;PETG\n; estimated printing time (normal mode) = 10m 0s\n');
  assert.equal(j.filaments.length, 2);
  assert.deepEqual([...j.filaments.map(f => f.type)], ['PLA', 'PETG']);
  near(j.gramsTotal, 5);
});

test('Bambu .gcode.3mf: multi plate, multi filament, entity-decoded object names', async () => {
  const j = await S.analyzeBytes('x.gcode.3mf', makeZip({ 'Metadata/slice_info.config': fx.bambu3mfSlice }));
  assert.equal(j.plates, 2);
  assert.equal(j.timeS, 6450);
  assert.equal(j.filaments.length, 3);
  near(j.gramsTotal, 26.5);
  assert.deepEqual([...j.objects], ['Benchy & Friends.stl']);
  assert.equal(S.matLabel(j), 'PLA+PETG');
});

test('stored (uncompressed) zip entries also work', async () => {
  const j = await S.analyzeBytes('x.3mf', makeZip({ 'Metadata/slice_info.config': fx.bambu3mfSlice }, { deflate: false }));
  assert.equal(j.plates, 2);
});

test('3MF with only embedded plate gcode falls back to parsing the gcode', async () => {
  const j = await S.analyzeBytes('x.3mf', makeZip({ 'Metadata/plate_1.gcode': fx.bambuGcode, 'Metadata/plate_2.gcode': fx.bambuGcode }));
  assert.equal(j.plates, 2);
  assert.equal(j.timeS, 9320);
  near(j.gramsTotal, 30.54);
});

test('unsliced 3MF gives an actionable error', async () => {
  await assert.rejects(S.analyzeBytes('u.3mf', makeZip({ '3D/3dmodel.model': '<model/>' })), /no slice data/);
});

test('bgcode, garbage zip, and empty text fail clearly instead of guessing', async () => {
  await assert.rejects(S.analyzeBytes('a.bgcode', new Uint8Array([0x47, 0x43, 0x44, 0x45, 1, 2])), /bgcode/i);
  await assert.rejects(S.analyzeBytes('bad.3mf', new Uint8Array([0x50, 0x4b, 1, 2, 3, 4, 5, 6])), /ZIP/);
  await assert.rejects(S.analyzeBytes('e.gcode', enc('G28\nG1 X1\n')), /No print time or filament/);
});

test('truncated zip central directory is reported, not crashed on', async () => {
  const z = makeZip({ 'Metadata/slice_info.config': fx.bambu3mfSlice });
  const cdOff = new DataView(z.buffer, z.byteOffset).getUint32(z.length - 22 + 16, true);
  z[cdOff] = 0; // corrupt central directory header signature
  await assert.rejects(S.analyzeBytes('t.3mf', z), /Corrupt ZIP/);
});

test('large G-code: only head and tail are read, stats in the tail still found', async () => {
  const filler = 'G1 X10 Y10 E0.5\n'.repeat(120000); // ~1.9 MB
  const text = '; generated by PrusaSlicer 2.7.1 on 2026-01-01\n' + filler + '; filament used [g] = 7.5\n; estimated printing time (normal mode) = 1h 0m 0s\n';
  const j = await S.analyzeBytes('big.gcode', enc(text));
  near(j.gramsTotal, 7.5);
  assert.equal(j.timeS, 3600);
});

test('cost math: material, energy, machine, waste and markup', () => {
  const st = { ...S.defaultSettings(), pricePerKg: 20, kwh: 0.2, watts: 100, machineRate: 1, wastePct: 10, markupPct: 50 };
  const job = { timeS: 7200, filaments: [{ type: 'PLA', grams: 100 }] };
  const c = S.computeCost(job, st);
  near(c.material, 2.2);          // 100 g * 1.1 * $20/kg
  near(c.energy, 0.04);           // 2 h * 100 W = 0.2 kWh * 0.2
  near(c.machine, 2);
  near(c.total, (2.2 + 0.04 + 2) * 1.5);
});

test('per-material prices override the default only for listed types', () => {
  const st = { ...S.defaultSettings(), priceByType: S.parseByType('petg=40, PLA = 10, bogus, TPU=x') };
  assert.deepEqual(Object.keys(st.priceByType).sort(), ['PETG', 'PLA']);
  const c = S.computeCost({ timeS: 0, filaments: [{ type: 'PETG', grams: 1000 }, { type: 'ABS', grams: 1000 }] }, st);
  near(c.material, 60);
});

test('receipt shows the numbers a maker needs', async () => {
  const j = await S.analyzeBytes('benchy.gcode.3mf', makeZip({ 'Metadata/slice_info.config': fx.bambu3mfSlice }));
  const st = S.defaultSettings();
  const r = S.receiptText(j, S.computeCost(j, st), st);
  assert.match(r, /1h 47m/);
  assert.match(r, /Filament 1 PLA\s+14\.88 g/);
  assert.match(r, /TOTAL/);
  assert.match(r, /2 plates/);
});

test('CSV escapes quotes/commas and neutralises spreadsheet formulas in file names', () => {
  const job = S.analyzeText('=HYPERLINK("x"),evil.gcode', fx.bambuGcode);
  const csv = S.toCSV([{ job }], S.defaultSettings());
  const line = csv.split('\r\n')[1];
  assert.ok(line.startsWith(`"'=HYPERLINK(""x""),evil.gcode"`), line);
  assert.equal(csv.split('\r\n')[0].split(',').length, 12);
});

